/*
 * Privacy model
 * -------------
 * Customer photos are never written to disk, S3 or the database. `renderCustomerPhoto`
 * keeps the photo in memory for the duration of the request, sends it to the AI
 * provider, returns the result to the caller and records only statistics.
 *
 * Sample rooms (uploaded or generated by an admin) are stored in S3, and their
 * renders are cached in S3 so a (sample, product) pair is paid for once.
 */

const ROOM_MAX_SIDE = Number(process.env.VISUALIZER_ROOM_MAX_SIDE || 1536);
const REF_MAX_SIDE = 1024;
// How many product photos are sent as references (each one costs input tokens).
const REFERENCE_IMAGES = Math.max(1, Math.min(3, Number(process.env.VISUALIZER_REFERENCE_IMAGES || 2)));
const BUCKET = process.env.AWS_S3_BUCKET || "";
const REGION = process.env.AWS_REGION || "";

// Short-lived in-memory cache of customer results so that "try another design → back"
// or a quick retry doesn't pay for the same (photo, product) twice.
const RESULT_CACHE_TTL_MS = Number(process.env.VISUALIZER_RESULT_CACHE_TTL_MS || 15 * 60 * 1000);
const RESULT_CACHE_MAX = 40;

type Source = "customer" | "admin" | "cli";

const s3Url = (key: string) => `https://${BUCKET}.s3.${REGION}.amazonaws.com/${key}`;

const putObject = async (key: string, body: Buffer, contentType: string) => {
  await s3Client.send(new PutObjectCommand({ Bucket: BUCKET, Key: key, Body: body, ContentType: contentType }));
  return s3Url(key);
};

const deleteObject = async (key?: string) => {
  if (!key) return;
  try {
    await s3Client.send(new DeleteObjectCommand({ Bucket: BUCKET, Key: key }));
  } catch (e) {
    console.warn("[visualizer] cannot delete", key, e);
  }
};

/** Raw S3 stream for proxied downloads (the bucket has no CORS, so the browser can't fetch it directly). */
export const getObjectStream = async (key: string) => {
  const res = await s3Client.send(new GetObjectCommand({ Bucket: BUCKET, Key: key }));
  return { body: res.Body as NodeJS.ReadableStream, contentType: res.ContentType || "image/jpeg", contentLength: res.ContentLength };
};

const getObject = async (key: string): Promise<Buffer> => {
  const res = await s3Client.send(new GetObjectCommand({ Bucket: BUCKET, Key: key }));
  const bytes = await res.Body!.transformToByteArray();
  return Buffer.from(bytes);
};

const fetchBuffer = async (url: string): Promise<{ buffer: Buffer; mime: string }> => {
  const res = await fetch(url);
  if (!res.ok) throw new Error(`Cannot download ${url}: ${res.status}`);
  const mime = res.headers.get("content-type") || "image/jpeg";
  return { buffer: Buffer.from(await res.arrayBuffer()), mime };
};

// HEIC/HEIF (iPhone photos) use the HEVC codec, which the bundled libvips cannot decode.
// The container starts with "....ftyp" followed by a brand such as heic, heix, hevc, mif1, msf1.
const isHeif = (buf: Buffer) => buf.length > 12 && buf.toString("ascii", 4, 8) === "ftyp" && /^(heic|heix|hevc|hevx|heim|heis|mif1|msf1)$/.test(buf.toString("ascii", 8, 12));

/** Decodes HEIC/HEIF to JPEG with the pure-JS libheif build (slow-ish, ~1–3 s, but works everywhere). */
const heifToJpeg = async (input: Buffer): Promise<Buffer> => {
  const { default: convert } = await import("heic-convert");
  const out = await convert({ buffer: input, format: "JPEG", quality: 0.92 });
  return Buffer.isBuffer(out) ? out : Buffer.from(out as ArrayBuffer);
};

const normalise = (input: Buffer, maxSide: number) =>
  sharp(input).rotate().resize({ width: maxSide, height: maxSide, fit: "inside", withoutEnlargement: true }).jpeg({ quality: 88 }).toBuffer();

/** Normalises a photo: fixes EXIF rotation, caps the size, re-encodes as JPEG (this also strips EXIF/GPS metadata). */
export const prepareRoomImage = async (input: Buffer): Promise<Buffer> => {
  if (isHeif(input)) return normalise(await heifToJpeg(input), ROOM_MAX_SIDE);
  try {
    return await normalise(input, ROOM_MAX_SIDE);
  } catch (err) {
    // Some HEIF files carry unusual brands; give the decoder one more chance before giving up.
    if (input.toString("ascii", 4, 8) === "ftyp") return normalise(await heifToJpeg(input), ROOM_MAX_SIDE);
    throw err;
  }
};

const prepareReference = async (input: Buffer): Promise<Buffer> =>
  sharp(input).rotate().resize({ width: REF_MAX_SIDE, height: REF_MAX_SIDE, fit: "inside", withoutEnlargement: true }).jpeg({ quality: 88 }).toBuffer();

/** Stores a prepared sample room photo and registers it (admin only). */
export const createSampleRoom = async (file: Buffer, opts: { title?: string; source?: Source } = {}) => {
  const prepared = await prepareRoomImage(file);
  const roomKey = `rooms/samples/${uuidv4()}.jpg`;
  const roomUrl = await putObject(roomKey, prepared, "image/jpeg");
  return RoomVisualization.create({
    roomKey,
    roomUrl,
    isSample: true,
    isActive: true,
    title: opts.title,
    status: "room",
    source: opts.source || "admin",
  });
};

/** Text-to-image for sample rooms (admin tool). */
export const generateSampleImage = async (prompt: string): Promise<Buffer> => {
  const apiKey = process.env.OPENAI_API_KEY;
  if (!apiKey) throw new Error("OPENAI_API_KEY is not set");
  const { model, quality } = openAIConfig();
  const res = await fetch("https://api.openai.com/v1/images/generations", {
    method: "POST",
    headers: { Authorization: `Bearer ${apiKey}`, "Content-Type": "application/json" },
    body: JSON.stringify({ model, prompt, size: "1536x1024", quality, output_format: "jpeg" }),
  });
  const text = await res.text();
  if (!res.ok) throw new Error(`OpenAI ${res.status}: ${text.slice(0, 300)}`);
  return Buffer.from(JSON.parse(text).data[0].b64_json, "base64");
};


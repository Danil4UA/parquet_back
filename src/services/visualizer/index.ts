const providers: Record<string, (i: Parameters<typeof renderWithOpenAI>[0]) => Promise<RenderOutput>> = {
  openai: renderWithOpenAI,
};

export const providerName = () => process.env.VISUALIZER_PROVIDER || "openai";

/** Public description of the current generation setup (shown in the admin dashboard). */
export const visualizerConfig = () => {
  const { model, quality, inputFidelity } = openAIConfig();
  return { provider: providerName(), model, quality, inputFidelity, referenceImages: REFERENCE_IMAGES, roomMaxSide: ROOM_MAX_SIDE };
};

export const classifyError = (err: unknown): RenderErrorKind => {
  const e = err as { name?: string; message?: string; kind?: RenderErrorKind };
  if (e?.kind) return e.kind;
  const message = String(e?.message || err);
  if (e?.name === "AbortError" || /abort|timed? ?out/i.test(message)) return "timeout";
  if (/^OpenAI \d{3}/.test(message)) return "provider";
  if (/input buffer|unsupported image|corrupt|bad image/i.test(message)) return "image";
  return "internal";
};

/* ------------------------------ framing ------------------------------
 * The provider only outputs 3:2, 2:3 or 1:1 canvases, while phones shoot 4:3. Instead of
 * cropping the customer's photo we pad it to the nearest canvas with mirrored edges, let the
 * model work on the padded picture, then cut the original frame back out of the result.
 * The shopper gets their whole photo back, in its own aspect ratio, nothing lost.
 */
interface Framing {
  image: Buffer;          // padded image sent to the provider
  size: ProviderCanvas;
  paddedWidth: number;
  paddedHeight: number;
  left: number;           // where the original sits inside the padded image
  top: number;
  width: number;
  height: number;
}

const CANVASES: { size: ProviderCanvas; ratio: number }[] = [
  { size: "1536x1024", ratio: 1.5 },
  { size: "1024x1536", ratio: 2 / 3 },
  { size: "1024x1024", ratio: 1 },
];

export const fitToProviderCanvas = async (input: Buffer): Promise<Framing> => {
  const { width, height } = await sharp(input).metadata();
  if (!width || !height) throw new Error("Cannot read image size");
  const ratio = width / height;
  // Nearest canvas by the amount of padding needed (compare log-ratios so 4:3 and 3:4 are symmetric).
  const canvas = CANVASES.reduce((best, c) => (Math.abs(Math.log(c.ratio / ratio)) < Math.abs(Math.log(best.ratio / ratio)) ? c : best));

  let paddedWidth = width;
  let paddedHeight = height;
  if (ratio < canvas.ratio) paddedWidth = Math.round(height * canvas.ratio);
  else paddedHeight = Math.round(width / canvas.ratio);
  const left = Math.floor((paddedWidth - width) / 2);
  const top = Math.floor((paddedHeight - height) / 2);

  const image =
    paddedWidth === width && paddedHeight === height
      ? input
      : await sharp(input)
          .extend({ left, right: paddedWidth - width - left, top, bottom: paddedHeight - height - top, extendWith: "mirror" })
          .jpeg({ quality: 88 })
          .toBuffer();

  return { image, size: canvas.size, paddedWidth, paddedHeight, left, top, width, height };
};

/** Cuts the original photo's frame back out of the provider's result. */
export const restoreFraming = async (result: Buffer, framing: Framing): Promise<Buffer> => {
  if (framing.left === 0 && framing.top === 0 && framing.paddedWidth === framing.width && framing.paddedHeight === framing.height) return result;
  const meta = await sharp(result).metadata();
  const sx = (meta.width || framing.paddedWidth) / framing.paddedWidth;
  const sy = (meta.height || framing.paddedHeight) / framing.paddedHeight;
  const left = Math.round(framing.left * sx);
  const top = Math.round(framing.top * sy);
  const width = Math.min(Math.round(framing.width * sx), (meta.width || 0) - left);
  const height = Math.min(Math.round(framing.height * sy), (meta.height || 0) - top);
  return sharp(result).extract({ left, top, width, height }).jpeg({ quality: 90 }).toBuffer();
};

/** Calls the AI provider for one (room image, product) pair. No storage involved. */
const runRender = async (roomImage: Buffer, product: IProductSchema): Promise<RenderOutput> => {
  const render = providers[providerName()];
  if (!render) throw new Error(`Unknown visualizer provider: ${providerName()}`);
  const framing = await fitToProviderCanvas(roomImage);

  const refs = await Promise.all(product.images.slice(0, REFERENCE_IMAGES).map((url) => fetchBuffer(url)));
  const referenceImages = await Promise.all(refs.map(async (r) => ({ buffer: await prepareReference(r.buffer), mime: "image/jpeg" })));
  const prompt = buildFloorPrompt({
    name: product.name?.en || (product.name as unknown as string),
    category: product.category,
    color: product.color,
    type: product.type,
    material: product.material,
    finish: product.finish,
    width: product.width,
    length: product.length,
  });

  const out = await render({ roomImage: framing.image, roomMime: "image/jpeg", referenceImages, prompt, size: framing.size });
  return { ...out, image: await restoreFraming(out.image, framing) };
};

/** Fills a render record from the provider output. */
const applyOutput = (record: IRoomVisualization, out: RenderOutput, started: number) => {
  record.set({
    status: "done",
    aiModel: out.model,
    quality: out.quality,
    usage: out.usage,
    estimatedCostUsd: estimateCostUsd(out.model, out.usage),
    durationMs: Date.now() - started,
  });
};

const applyFailure = (record: IRoomVisualization, err: unknown, started: number) => {
  record.set({
    status: "failed",
    error: String((err as Error)?.message || err).slice(0, 1000),
    errorKind: classifyError(err),
    durationMs: Date.now() - started,
  });
};

/* ------------------------------ customer photos ------------------------------ */

interface CachedResult { image: Buffer; mime: string; expires: number }
const resultCache = new Map<string, CachedResult>();

const cacheKey = (prepared: Buffer, productId: string) => `${createHash("sha256").update(prepared).digest("hex")}:${productId}`;

const cacheGet = (key: string) => {
  const hit = resultCache.get(key);
  if (!hit) return undefined;
  if (hit.expires < Date.now()) { resultCache.delete(key); return undefined; }
  return hit;
};

const cacheSet = (key: string, value: Omit<CachedResult, "expires">) => {
  const now = Date.now();
  for (const [k, v] of resultCache) if (v.expires < now) resultCache.delete(k);
  while (resultCache.size >= RESULT_CACHE_MAX) resultCache.delete(resultCache.keys().next().value as string);
  resultCache.set(key, { ...value, expires: now + RESULT_CACHE_TTL_MS });
};

export interface CustomerRenderResult {
  image: Buffer;
  mime: string;
  durationMs: number;
  cached: boolean;
}

/** Writes a failed record for an upload that never reached the AI (bad file, too large), so the admin can see it. */
export const recordRejectedUpload = async (message: string, ip?: string, productId?: string) => {
  try {
    await RoomVisualization.create({
      isSample: false,
      productId,
      provider: providerName(),
      status: "failed",
      errorKind: "image",
      error: message.slice(0, 1000),
      durationMs: 0,
      ip,
      source: "customer",
    });
  } catch (e) {
    console.warn("[visualizer] cannot record rejected upload", e);
  }
};

/**
 * Renders a product floor into a customer's photo without storing the photo or the result.
 * Only a statistics record (no images) is written to the database.
 */
export const renderCustomerPhoto = async (photo: Buffer, productId: string, opts: { ip?: string } = {}): Promise<CustomerRenderResult> => {
  const started = Date.now();
  let prepared: Buffer;
  try {
    prepared = await prepareRoomImage(photo);
  } catch (err) {
    const detail = String((err as Error)?.message || err);
    console.warn("[visualizer] cannot decode photo:", detail, { ip: opts.ip, bytes: photo.length });
    await recordRejectedUpload(`Cannot decode photo (${photo.length} bytes): ${detail}`, opts.ip, productId);
    throw Object.assign(new Error("Unsupported or corrupt image"), { status: 400, kind: "image" as RenderErrorKind });
  }

  const key = cacheKey(prepared, productId);
  const hit = cacheGet(key);
  if (hit) return { image: hit.image, mime: hit.mime, durationMs: Date.now() - started, cached: true };

  const product = await Product.findById(productId);
  if (!product) throw Object.assign(new Error("Product not found"), { status: 404 });

  const record = await RoomVisualization.create({
    isSample: false,
    productId,
    provider: providerName(),
    status: "pending",
    ip: opts.ip,
    source: "customer",
  });

  try {
    const out = await runRender(prepared, product);
    applyOutput(record, out, started);
    await record.save();
    cacheSet(key, { image: out.image, mime: out.mime });
    return { image: out.image, mime: out.mime, durationMs: Date.now() - started, cached: false };
  } catch (err) {
    applyFailure(record, err, started);
    await record.save();
    throw err;
  }
};

/* ------------------------------- sample rooms -------------------------------- */

/** Renders a product floor into a sample room. Cached in S3 per (room, product) unless `force`. */
export const renderRoom = async (roomKey: string, productId: string, opts: { ip?: string; source?: Source; force?: boolean } = {}): Promise<IRoomVisualization> => {
  if (!opts.force) {
    const cached = await RoomVisualization.findOne({ roomKey, productId, status: "done" });
    if (cached) return cached;
  }

  const room = await RoomVisualization.findOne({ roomKey, status: "room", isSample: true });
  if (!room) throw Object.assign(new Error("Room not found"), { status: 404 });

  const product = await Product.findById(productId);
  if (!product) throw Object.assign(new Error("Product not found"), { status: 404 });

  const record = await RoomVisualization.create({
    roomKey,
    roomUrl: room.roomUrl,
    isSample: true,
    productId,
    provider: providerName(),
    status: "pending",
    ip: opts.ip,
    source: opts.source || "customer",
  });

  const started = Date.now();
  try {
    const roomImage = await getObject(roomKey);
    const out = await runRender(roomImage, product);
    const resultKey = `${roomKey.replace(/\.jpg$/, "")}/${productId}-${Date.now().toString(36)}.jpg`;
    const resultUrl = await putObject(resultKey, out.image, out.mime);
    applyOutput(record, out, started);
    record.set({ resultKey, resultUrl });
    await record.save();
    return record;
  } catch (err) {
    applyFailure(record, err, started);
    await record.save();
    throw err;
  }
};

/** Admin: drop a sample render (S3 + record) and run it again. Older renders for the pair are removed too. */
export const regenerateRender = async (renderId: string) => {
  const render = await RoomVisualization.findById(renderId);
  if (!render || !render.productId || !render.roomKey || !render.isSample) {
    throw Object.assign(new Error("Only sample-room renders can be regenerated"), { status: 404 });
  }
  const { roomKey, productId } = render;
  const siblings = await RoomVisualization.find({ roomKey, productId, status: { $in: ["done", "failed"] } });
  for (const doc of siblings) {
    await deleteObject(doc.resultKey);
    await doc.deleteOne();
  }
  return renderRoom(roomKey, productId, { source: "admin", force: true });
};

export const deleteRender = async (renderId: string) => {
  const render = await RoomVisualization.findById(renderId);
  if (!render || render.status === "room") throw Object.assign(new Error("Render not found"), { status: 404 });
  await deleteObject(render.resultKey);
  await render.deleteOne();
};

/** Admin: delete a sample room together with everything rendered from it. */
export const deleteRoom = async (roomId: string) => {
  const room = await RoomVisualization.findById(roomId);
  if (!room || room.status !== "room") throw Object.assign(new Error("Room not found"), { status: 404 });
  const renders = await RoomVisualization.find({ roomKey: room.roomKey, status: { $ne: "room" } });
  for (const doc of renders) {
    await deleteObject(doc.resultKey);
    await doc.deleteOne();
  }
  await deleteObject(room.roomKey);
  await room.deleteOne();
};

/* ------------------------------ one-time cleanup ------------------------------ */

const legacyCustomerFilter = { isSample: false, $or: [{ roomKey: { $exists: true } }, { resultKey: { $exists: true } }] };

/** How many customer images from before the privacy change are still stored. */
export const countStoredCustomerImages = () => RoomVisualization.countDocuments(legacyCustomerFilter);

/**
 * Deletes every customer photo and customer result stored before the privacy change.
 * Room records are removed; render records are kept for statistics but stripped of images.
 */
export const purgeStoredCustomerImages = async () => {
  let files = 0;
  let rooms = 0;
  let renders = 0;

  const docs = await RoomVisualization.find(legacyCustomerFilter);
  for (const doc of docs) {
    if (doc.status === "room") {
      await deleteObject(doc.roomKey); files += 1;
      await doc.deleteOne(); rooms += 1;
    } else {
      if (doc.resultKey) { await deleteObject(doc.resultKey); files += 1; }
      await RoomVisualization.updateOne({ _id: doc._id }, { $unset: { roomKey: 1, roomUrl: 1, resultKey: 1, resultUrl: 1 } });
      renders += 1;
    }
  }
  return { files, rooms, renders };
};
